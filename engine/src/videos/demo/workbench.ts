// Заглушка описи для монтажного стола.
//
// Стол открывает ровно один модуль — `src/workbench.ts`, а тот реэкспортирует
// опись нужного ролика. Пока своих роликов нет, он смотрит сюда.
//
// Почему заглушка, а не демо-ролик: опись требует речи (`speech`), слов
// караоке и звуковых реплик, то есть данных конкретной записи. У демо-
// композиций записи нет — они показывают движок, а не ролик. Собрать из них
// честную опись нельзя, а подсунуть путь к несуществующему wav — значит
// получить пустой таймлайн и полчаса на выяснение, почему.
//
// Что делать: собери первый ролик, и опись появится рядом с ним —
// `src/videos/video-NN/workbench.ts`. Переключение на неё — командой
// `./scripts/workbench.sh NN`, она сама перепишет строку в `src/workbench.ts`.
// Как устроена опись и почему в ней нет своих таймингов — `lib/workbench.tsx`.
