import { Config } from '@remotion/cli/config';

// Качество кадров и кодека (2026-09-04, по ревью): раньше кадры снимались
// JPEG quality 80 (дефолт Remotion) и жались CRF 18 — тёмный video-150 весил
// 1.5 Мбит/с, Instagram перекодировал его ещё раз и мылил градиенты и мелкий
// текст. Теперь JPEG 95 + CRF 16: битрейт выше, артефактов на краях букв
// нет, рендер медленнее на единицы процентов. Флагами командной строки
// (--jpeg-quality, --crf) эти значения НЕ понижать — кроме ЧЕРНОВОГО рендера
// под QA (`scripts/qa-sheet.sh draft`): там кадры режутся в тайлы 360px, и
// качество понижено сознательно, см. комментарий в самом скрипте.
Config.setVideoImageFormat('jpeg');
Config.setJpegQuality(95);
Config.setCrf(16);
Config.setOverwriteOutput(true);
Config.setChromiumOpenGlRenderer('angle');

// Параллельность рендера (правка 2026-10-07). Было 4 при 12 потоках —
// перестраховка с машины-донора. Здесь i5-1235U: 2 производительных ядра +
// 8 экономичных, 12 потоков. 6 — компромисс: больше задействует E-ядра, но
// не загоняет машину в троттлинг (чип 15 Вт, под полной нагрузкой частоты
// падают и выигрыш съедается). ⚠ Число подобрано расчётом, НЕ замером:
// на первом же ролике снять время рендера и сверить с 4 и 8.
Config.setConcurrency(6);

// Шрифты грузятся локально (@remotion/fonts, без сети) через delayRender —
// таймаут поднят до 120с с запасом (правило remotion-ecosystem.md п.6:
// google-fonts запрещён, только локальные .woff2).
Config.setDelayRenderTimeoutInMilliseconds(120000);
