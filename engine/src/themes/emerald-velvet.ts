// Тема «Emerald Velvet» — замена визуального языка, не вариант emerald.
// Паспорт темы со всеми числами и правилами — library/velvet-theme.md.
//
// Три отличия от emerald, из которых растёт всё остальное:
//  1. Фон перестаёт быть плоским: база + асимметричные пятна свечения +
//     виньетка + зерно (у emerald — один #061710 и статичная виньетка).
//  2. Карточка получает тень и inset-хайрлайн: у emerald cardShadow 'none',
//     то есть в кадре физически ноль слоёв глубины.
//  3. Акцент уходит с кислотного лайма #B6F24D на изумруд #34D399, а вторым
//     акцентом вводится шампань #D8C9A3 — ТОЛЬКО линией и мелким капсом.
//     Лайм на тёмно-зелёном даёт «неон поверх зелёного», изумруд — один
//     материал с фоном.
//
// ⚠️ Палитра расходится с нынешними обложками Telegram и Дзена
// (свой файл бренда). Их надо подтянуть следом, иначе
// канал перестанет читаться как одно целое.
//
// Каркас зон скопирован у noir/emerald без изменений: полоса караоке тёмных
// тем 1450–1620 — safe space интерфейса Reels/Shorts, её трогать нельзя.
import type { Theme } from './types';

/** Второй акцент. Выведен в константу, потому что нужен и в hairline темы,
 * и в подписях Oswald: два места, одно значение. */
export const CHAMPAGNE = '#D8C9A3';

/** Цвета пятен свечения фона. Вынесены в токены темы, потому что блоки
 * задают СВОИ пятна (тон кадра — монтажная величина), но цвет источника
 * света во всех блоках обязан быть один: разные оттенки зелени на соседних
 * склейках читаются как смена темы, а не как смена тона.
 *
 * Светлота поднята против первой редакции (#0E6B4A / #0C5A57, L 24 % и 20 %)
 * примерно на треть — до L 32 % и 28 %. Повод: на приёмке пробника блоки
 * B3 и B5 читались плоским чёрным, пятна в кадре не различались вовсе. Лечится именно светлотой, а не
 * плотностью: density гонит ТОН блока и обязан оставаться разным у соседних
 * блоков, иначе склейка перестаёт меняться по тону. */
export const GLOW = {
  emerald: '#139067',
  teal: '#117E78',
} as const;

export const emeraldVelvetTheme: Theme = {
  id: 'emerald-velvet',
  colors: {
    bg: '#04100B',
    ink: '#EAF4ED',
    muted: '#8FAEA0',
    ghost: 'rgba(234,244,237,0.26)',
    card: '#0A1C14',
    cardBorder: '#17352A',
    // Тень + inset-хайрлайн сверху: карточка перестаёт быть плашкой и
    // становится предметом, лежащим НАД фоном. Inset идёт первым, иначе
    // внешняя тень рисуется поверх светлой кромки.
    cardShadow:
      'inset 0 1px 0 rgba(234,244,237,.07), 0 28px 80px -24px rgba(0,0,0,.74)',
    mark: '#34D399',
    markText: '#04100B',
    blue: '#4CC9F0',
    green: '#34D399',
    orange: '#D97757', // коралловый спарк Claude — остаётся как акцент-элемент
    purple: '#8957E5',
    red: '#E5484D',
    flashA: '#0A1C14',
    flashB: '#17352A',
  },
  fontInter: 'Inter, "Inter Placeholder", sans-serif',
  fontMono: '"JetBrains Mono", ui-monospace, SFMono-Regular, monospace',
  safe: {
    contentTop: 300,
    contentBottom: 1100,
    capTop: 1450,
    capBottom: 1620,
  },
  caption: {
    usePillBackground: false,
    fontSize: 60, // константа канала, не трогаем
    textShadow: '0 2px 16px #04100BCC',
  },
  depth: {
    // Пятна по умолчанию — отправная точка; каждый блок/сцена задаёт свои
    // через проп BackdropDepth, потому что тон кадра это монтажная величина.
    glows: [
      { color: GLOW.emerald, radius: 760, x: 760, y: 420, opacity: 0.42 },
      { color: GLOW.teal, radius: 540, x: 180, y: 1520, opacity: 0.3 },
    ],
    vignette:
      'radial-gradient(ellipse 78% 58% at 50% 46%, rgba(0,0,0,0) 42%, rgba(0,0,0,0.62) 100%)',
    grain: { opacity: 0.055, scale: 1.6 },
    hairline: CHAMPAGNE,
  },
  type: {
    // Иерархия: 136/74 = 1,84; 164/74 = 2,22. У emerald было 80/64 = 1,25.
    scale: { hero: 164, title: 136, lead: 74, body: 52, mono: 44, label: 42 },
    display: '"Playfair Display", "PT Serif", Georgia, serif',
    // label именно 42, а не 38: линт даёт WARN на fontSize < 40.
    label: 'Oswald, "Inter", sans-serif',
  },
};

/** Кнопка-акцент темы: изумруд на тёмном, текст — цветом фона. */
export const EMERALD_VELVET_BTN = emeraldVelvetTheme.colors.mark;
