// TargetBox — выделение цели наезда. Правило 28 в CLAUDE.md.
//
// Зачем компонент появился (правка 2026-10-07, по разбору тестовых роликов):
// правило 19 требовало наезда PageCam на цель, правило 22 — приглушить вокруг
// неё мелкий текст, но НИЧТО не требовало показать саму цель. На экране камера
// куда-то подъезжала, а зритель не понимал, на что смотреть: в кадре
// оставалась страница целиком, просто крупнее. Рамка закрывает именно этот
// разрыв — «вот это слово / эта цифра / эта строка, о ней речь».
//
// Ставится ДЕТЕЙМ внутрь <PageCam>: у PageCam проп children — это оверлеи в
// системе координат самого источника (page-space CSS px), поэтому рамка едет
// вместе с камерой и остаётся приклеенной к цели.
//
//   <PageCam src={...} pageH={2400} srcW={1080} viewportW={1080} viewportH={1920} keys={CAM}>
//     <TargetBox x={120} y={840} w={620} h={96} zoom={2.4} theme={theme} from={38} />
//   </PageCam>
//
// Главная грабля, из-за которой здесь столько математики: контейнер страницы
// внутри PageCam масштабируется transform: scale(zoom). Значит ЛЮБАЯ
// толщина, заданная в page-px, на экране умножается на zoom — рамка 6px при
// наезде ×3 превращается в полосу 18px и съедает цель. Поэтому линия и
// скругление делятся на zoom, а зазор pad остаётся в page-px: он описывает
// отступ от текста В МАКЕТЕ СТРАНИЦЫ, и мерить его надо там же, где меряли
// цель.
import React from 'react';
import { interpolate, useCurrentFrame, Easing } from 'remotion';
import type { Theme } from '../themes/types';

export const TargetBox: React.FC<{
  /** Цель в координатах ИСТОЧНИКА (пиксели самого скрина/клипа), замеренные
   * пипеткой по краю смыслового блока — не на глаз. Правило 28: границы не
   * режут строку и не прихватывают соседний абзац. */
  x: number;
  y: number;
  w: number;
  h: number;
  /** zoom камеры в момент, когда рамка показывается, — берётся из последнего
   * CamKey наезда. Нужен, чтобы линия и скругление не «толстели» при наезде.
   * Рамка появляется в КОНЦЕ движения, когда камера уже стоит, поэтому одного
   * числа достаточно. */
  zoom: number;
  theme: Theme;
  /** Кадр появления (в системе отсчёта сцены). По умолчанию 0. */
  from?: number;
  /** 'frame' — только рамка. 'spotlight' — рамка + затемнение всего
   * остального: закрывает правило 22 (мелкий текст вокруг цели приглушён)
   * одним движением, отдельный скрим рисовать не нужно. */
  mode?: 'frame' | 'spotlight';
  /** Зазор между целью и линией, в page-px. Меньше 8 ставить нельзя: линия
   * прижимается к буквам и читается как подчёркивание чужой строки. */
  pad?: number;
  /** Толщина линии в ЭКРАННЫХ px (делится на zoom внутри). */
  stroke?: number;
  /** Плотность затемнения в режиме spotlight, 0..1. */
  scrim?: number;
  /** Цвет линии. По умолчанию — акцент-элемент темы: в light коралловый,
   * в emerald лайм берётся из mark (см. ниже). */
  color?: string;
  /** Абсолютный кадр композиции, когда TargetBox стоит внутри <Sequence>
   * (Sequence пересчитывает useCurrentFrame — тот же приём, что в PageCam). */
  frame?: number;
}> = ({
  x,
  y,
  w,
  h,
  zoom,
  theme,
  from = 0,
  mode = 'frame',
  pad = 12,
  stroke = 5,
  scrim = 0.6,
  color,
  frame: frameProp,
}) => {
  const ownFrame = useCurrentFrame();
  const frame = frameProp ?? ownFrame;
  const t = frame - from;

  // Акцент по теме: на тёмной emerald лайм (mark) читается лучше коралла,
  // на светлой наоборот — коралл заметнее жёлтого маркера караоке. Явный
  // color перебивает обе ветки.
  //
  // ⚠ Проверено на пруфе 2026-10-07 (TargetBoxLight): контраст рамки зависит
  // не от темы ролика, а от САМОГО СКРИНА — она лежит поверх него. Коралл
  // светлой темы на тёмном скрине Obsidian с жёлтыми заголовками читался
  // вяло. Поэтому: тёмный скрин под светлой темой → либо задать `color`
  // явно, либо брать mode="spotlight" (на том же кадре цель вышла заметно
  // чище). Дефолт по теме — удобная отправная точка, не гарантия контраста.
  const line = color ?? (theme.id === 'light' ? theme.colors.orange : theme.colors.mark);

  // Появление: 9 кадров (0.3с при 30fps) — быстрее читается как «щёлк»,
  // медленнее начинает выглядеть как отдельное событие и нарушает правило 3
  // (одна точка внимания). Лёгкий «перелёт» масштаба 1.06 → 1 даёт щелчок
  // без удара по кадру; правило 7 (стробов нет) не задето — мигает не фон,
  // а один объект.
  const IN = 9;
  const appear = interpolate(t, [0, IN], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
    easing: Easing.out(Easing.cubic),
  });
  const pop = interpolate(t, [0, IN], [1.06, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
    easing: Easing.out(Easing.cubic),
  });

  // Рамка стоит до конца сцены (правило 8: герой сцены живёт ≥1.2с после
  // полного появления) — ухода здесь намеренно нет, уводит её срез сцены.
  if (t < 0) return null;

  // Прямоугольник рамки = цель + зазор со всех сторон. Все отступы в page-px,
  // потому что и цель замерена в page-px.
  const bx = x - pad;
  const by = y - pad;
  const bw = w + pad * 2;
  const bh = h + pad * 2;

  // Компенсация масштаба: на экране линия должна быть ровно `stroke` px при
  // любом zoom.
  const lineW = stroke / zoom;
  const radius = 14 / zoom;

  return (
    <div
      style={{
        position: 'absolute',
        left: bx,
        top: by,
        width: bw,
        height: bh,
        borderRadius: radius,
        // outline, а не border: рисуется ПОВЕРХ и НАРУЖУ бокса, не меняя его
        // размер. С border пришлось бы вычитать толщину из left/top вручную,
        // и при каждой правке zoom рамка уезжала бы с цели на пару пикселей.
        outline: `${lineW}px solid ${line}`,
        outlineOffset: 0,
        // Затемнение всего кадра, кроме цели: тень с огромным spread'ом
        // заливает всё за пределами бокса. Дешевле четырёх div'ов по сторонам
        // и не требует знать размер страницы.
        boxShadow:
          mode === 'spotlight'
            ? `0 0 0 ${20000 / zoom}px rgba(0,0,0,${scrim * appear})`
            : undefined,
        opacity: appear,
        transform: `scale(${pop})`,
        transformOrigin: 'center center',
        // Рамка — оверлей: клики и события ей не нужны, а pointerEvents: none
        // страхует от перехвата в Remotion Studio при отладке.
        pointerEvents: 'none',
      }}
    />
  );
};
