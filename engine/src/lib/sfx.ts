// Привязка SFX ко кадрам: относительные якоря и две поправки смещения.
//
// Перенос правил §4.5 и §4.6 из references/sound-design.md проекта
// video-shotcraft (Apache-2.0, см. NOTICE) на наш движок.
// ГРОМКОСТЬ SFX живёт отдельно — helpers.ts, sfxGain(). Здесь только ВРЕМЯ.
//
// Зачем вообще: между «хочу, чтобы удар совпал с кадром N» и тем, что
// слышно в сданном файле, стоят два смещения, и они складываются.
// Замер автора базового комплекта: самый тяжёлый удар опаздывал на 0,27с — это читается
// как рассинхрон. На контактном листе такое не видно вообще: кадры целы,
// а звук мимо. Поэтому кадр SFX не пишется числом, а считается.
//
//   from = целевой кадр пика − лаг пика сэмпла − смещение дорожки рендера
//
// Поправка 1 — смещение аудиодорожки рендера (общее для всего пайплайна).
//   AAC-кодер подмешивает в начало дорожки «прогревочные» сэмплы
//   (encoder priming): на 48 кГц это обычно 1024-2112 сэмплов, то есть
//   0,6-1,3 кадра при 30 fps. Величина зависит от связки «версия Remotion +
//   кодек + частота + контейнер» — она НЕ константа и предполагать её нельзя.
//   Замеряется один раз на пайплайн: scripts/audio-offset.py.
// Поправка 2 — лаг пика самого сэмпла (у каждого файла свой).
//   У многих сэмплов энергия пика не в начале файла: нарастающая атака,
//   вдох перед удаpом. Выровнять по началу файла = опоздать. Замер — в
//   scripts/sfx-peaks.py, таблица — sfxPeaks.ts (генерируется, не править).
//   (sfx-catalog.sh — это про ГРОМКОСТЬ, пики файлов для формулы volume.)

import { SFX_PEAK_LAG_F } from './sfxPeaks';

/** Смещение аудиодорожки сданного файла, в кадрах при 30 fps.
 *
 * ЗАМЕРЕНО 2026-10-14. Пайплайн: Remotion 4.0.520 + ffmpeg AAC 48 кГц mp4,
 * мастеринг `alimiter` + повторное кодирование в AAC 192k.
 * Эталон замера — композиция AudioOffsetProbe, три зонда
 * (impact/bass-hit-short, ui/pop, ui/ui-click-tone), качество корреляции
 * 1.00 у каждого, разброс 0.02 кадра.
 *
 * Два звена цепочки, и они складываются:
 *   рендер Remotion         +1.28 кадра (43 мс) — ровно AAC encoder priming
 *                                                2048 сэмплов на 48 кГц;
 *   + мастеринг (ffmpeg)    +0.15 кадра (5 мс)  — второе кодирование в AAC.
 *   = сданный финал         +1.43 кадра (48 мс)
 *
 * Берём число ФИНАЛА: зритель слышит мастеринговый файл, а не рендер.
 * Если когда-нибудь мастеринг уйдёт из конвейера — вернуть 1.28.
 *
 * Перезамерять при смене любого звена (версия Remotion, кодек, частота,
 * контейнер, параметры мастеринга): старую константу на новый пайплайн
 * переносить нельзя — priming зависит от кодера (ffmpeg aac ≈1024,
 * fdk-aac 2048, Apple ≈2112 сэмплов).
 *   ./scripts/render.sh AudioOffsetProbe
 *   python scripts/audio-offset.py engine/out/audiooffsetprobe.mp4 --probe ... */
export const OUTPUT_AUDIO_OFFSET_F = 1.43;

/** Кадр для <Sequence from={...}> под SFX.
 *
 * @param targetPeakF кадр, НА КОТОРОМ ДОЛЖЕН БЫТЬ СЛЫШЕН пик звука.
 *   Пишется относительно начала сцены: `SCENES[3].from + 12`, а в ролике
 *   под биты музыки — `beatF(28)`. Голое число — брак (правило §4.5:
 *   сдвинешь одну сцену, и вся таблица SFX поедет; у нас это уже стоило
 *   трёх кругов правок на video-02-emerald).
 * @param src путь сэмпла от public/, как в staticFile() — по нему
 *   берётся лаг пика из замеренной таблицы.
 *
 * durationInFrames поправкой НЕ двигается: окно уехало вперёд целиком,
 * начало и конец встали на место вместе. Удлинить окно у сэмпла, который
 * обрезан явным durationInFrames, значит выпустить в ролик тот хвост,
 * который и обрезали.
 *
 * Math.max(0, ...) значит, что в первых ~2 кадрах ролика компенсация
 * физически не укладывается. Поэтому сильную долю в самое начало не ставить
 * (в хуке по правилу 29 событие и так идёт с f8, а не с f0). */
export const sfxFrom = (targetPeakF: number, src: string): number =>
  Math.max(0, Math.round(targetPeakF - (SFX_PEAK_LAG_F[src] ?? 0) - OUTPUT_AUDIO_OFFSET_F));

// ── Сетка битов (для роликов, смонтированных под музыку) ────────────────────
// ⚠ ЗАДЕЛ, в конвейере НЕ используется (решение автора 2026-10-14). Мы
// ролики под биты музыки не монтируем: BGM у нас фон на 14–18 dB ниже речи,
// а сцены режутся по битам РЕЧИ (правило 23). Фабрика оставлена потому, что
// арифметика сетки — то место, где легко ошибиться дважды (см. ниже про
// двойное применение поправки), и переписывать её заново смысла нет.
// Методики (music-beat-sync.md каталога приёмов → library/beat-sync.md, у нас не заведён) и скрипта
// анализа дорожки (beat-grid.py) у нас пока НЕТ: решим монтировать под
// музыку — сначала они, потом эта фабрика.

export type BeatGrid = {
  /** Бит → секунда дорожки сданного ролика. */
  beatT: (n: number) => number;
  /** Бит → кадр. Округление ровно одно и ровно здесь. */
  beatF: (n: number) => number;
  /** Бит → кадр ВНУТРИ сцены (для локальных анимаций сцены). */
  localBeat: (shot: { from: number }, n: number) => number;
  bpm: number;
};

/** Собирает сетку битов из замеренных констант.
 *
 * sourceBeat0 и period — истина замера источника (analysis/beat_data.json),
 * они не правятся НИКОГДА: это база аудита. Смещение дорожки рендера живёт
 * отдельным слагаемым. Если смешать их в одну константу, то при смене кодека
 * или повторном анализе поправка применится дважды.
 *
 * Все расчёты в секундах с плавающей точкой; в кадры переводим последним
 * шагом. Округлить раньше — ошибка покатится по конвейеру снежным комом. */
export const makeBeatGrid = (c: {
  /** t0 из замера источника, секунды (когда появится beat-grid.py —
   * из его отчёта; руками это число не выдумывают). */
  sourceBeat0: number;
  /** T — длина бита, секунды (bpm = 60 / period). */
  period: number;
  fps: number;
  /** Смещение дорожки рендера, секунды (то же, что OUTPUT_AUDIO_OFFSET_F,
   * но в секундах: outputOffsetSec = OUTPUT_AUDIO_OFFSET_F / fps). */
  outputOffsetSec?: number;
}): BeatGrid => {
  const { sourceBeat0, period, fps, outputOffsetSec = 0 } = c;
  const beatT = (n: number) => sourceBeat0 + outputOffsetSec + n * period;
  const beatF = (n: number) => Math.round(beatT(n) * fps);
  return {
    beatT,
    beatF,
    localBeat: (shot, n) => beatF(n) - shot.from,
    bpm: 60 / period,
  };
};
