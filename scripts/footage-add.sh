#!/usr/bin/env bash
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/tools/env.sh"   # прослойка окружения, см. tools/env.sh
# ══════════════════════════════════════════════════════════════
# footage-add.sh (reelcraft) — принять сырой исходник в банк живого футажа.
# Запуск: scripts/footage-add.sh <файл> <имя-клипа> [опции]
#
#   --from ЧЧ:ММ:СС[.мс]  начало куска (по умолчанию с нуля)
#   --to   ЧЧ:ММ:СС[.мс]  конец куска
#   --dur  N              длительность в секундах вместо --to
#   --crop vertical       центральный кроп в 9:16 (из ландшафтной съёмки)
#   --width N             ширина на выходе (по умолчанию как в исходнике, но
#                         не больше 1080 — в кадре ролика больше не нужно)
#   --force               перезаписать клип с тем же именем
#   --no-sheet            не собирать контактный лист
#
# Зачем скрипт вообще нужен — три причины, каждая стоила бы круга правок:
#
#  1. ЧАСТОТА КАДРОВ. Запись с телефона идёт с переменной частотой (VFR).
#     Remotion при рендере просит у клипа конкретный кадр, и на VFR-дорожке
#     он получает «ближайший» — картинка дёргается на ровном движении, а на
#     контактном листе это не видно вообще. Поэтому всё, что попадает в банк,
#     приводится к CFR 30 fps (той же, что у композиции).
#
#  2. ЗВУК. У клипа своя дорожка, у ролика — речь −14 LUFS. Если дорожка
#     доедет до композиции, замеры мастеринга (volumedetect окном речи)
#     начнут врать. Звук снимается здесь, на входе, а не в сцене.
#
#  3. ОПИСЬ. Правило банка: «без строки в таблице клип для агента не
#     существует» (footage/catalog.md). Руками строку дописывать забывают,
#     поэтому скрипт дописывает её сам — с техникой, длительностью и
#     размером, а описание «что на экране» остаётся автору.
#
# Контактный лист собирается сразу: кадры клипа надо посмотреть ГЛАЗАМИ до
# того, как он попал в сториборд (норма «Скриншоты и футаж» в CLAUDE.md).
# ══════════════════════════════════════════════════════════════
set -euo pipefail
cd "$(dirname "$0")/.."

SRC="${1:-}"
NAME="${2:-}"
if [ -z "$SRC" ] || [ -z "$NAME" ]; then
  echo "✗ Запуск: scripts/footage-add.sh <файл> <имя-клипа> [--from ..] [--to ..] [--dur N] [--crop vertical] [--width N] [--force] [--no-sheet]"
  exit 1
fi
[ -f "$SRC" ] || { echo "✗ Нет файла: $SRC"; exit 1; }
shift 2

# Имя клипа — латиница, цифры и дефис: путь уезжает в staticFile() и
# в имена ассетов ролика, кириллица и пробелы там ломают пути.
case "$NAME" in
  *[!a-z0-9-]*) echo "✗ Имя клипа — только строчная латиница, цифры и дефис: $NAME"; exit 1 ;;
esac

FROM=""; TO=""; DUR=""; CROP=""; WIDTH=""; FORCE=0; SHEET=1
while [ $# -gt 0 ]; do
  case "$1" in
    --from)  FROM="${2:-}"; shift 2 ;;
    --to)    TO="${2:-}"; shift 2 ;;
    --dur)   DUR="${2:-}"; shift 2 ;;
    --crop)  CROP="${2:-}"; shift 2 ;;
    --width) WIDTH="${2:-}"; shift 2 ;;
    --force) FORCE=1; shift ;;
    --no-sheet) SHEET=0; shift ;;
    *) echo "✗ Неизвестная опция: $1"; exit 1 ;;
  esac
done

OUT="footage/clips/${NAME}.mp4"
SHEET_PNG="footage/_sheets/${NAME}.png"
if [ -f "$OUT" ] && [ "$FORCE" -eq 0 ]; then
  echo "✗ Клип уже есть: $OUT (перезаписать — --force)"
  exit 1
fi
mkdir -p footage/clips footage/_sheets

# ── параметры исходника ───────────────────────────────────────────────────────
read -r SRC_W SRC_H SRC_FPS <<EOF
$(ffprobe -v error -select_streams v:0 -show_entries stream=width,height,r_frame_rate -of csv=p=0 "$SRC" | tr ',' ' ')
EOF
[ -n "${SRC_W:-}" ] || { echo "✗ Не читается видеодорожка: $SRC"; exit 1; }
echo "→ Исходник: ${SRC_W}×${SRC_H}, ${SRC_FPS} fps"

# ── фильтры: кроп, масштаб, частота кадров ───────────────────────────────────
# Порядок важен: сначала кроп (режем по исходным пикселям), потом масштаб,
# и только в конце fps — иначе дублированные кадры попадут под интерполяцию.
VF=""
if [ "$CROP" = "vertical" ]; then
  # Центральный кроп в 9:16. Берём максимум, что влезает по высоте.
  VF="crop='min(iw,ih*9/16)':ih:(iw-min(iw,ih*9/16))/2:0"
fi
TARGET_W="${WIDTH:-}"
if [ -z "$TARGET_W" ] && [ "$SRC_W" -gt 1080 ]; then
  # Ширина сверх 1080 в кадре ролика не нужна: рабочая ширина носителя 1000,
  # полный кадр 1080. Лишние пиксели — только вес и время рендера.
  TARGET_W=1080
fi
if [ -n "$TARGET_W" ]; then
  # -2 = высота кратна 2 (требование yuv420p).
  VF="${VF:+$VF,}scale=${TARGET_W}:-2:flags=lanczos"
fi
VF="${VF:+$VF,}fps=30"

# ── обрезка ──────────────────────────────────────────────────────────────────
# -ss ПЕРЕД -i: быстрый поиск по ключевым кадрам. Точность до кадра здесь не
# нужна — кусок всё равно подрезается в сцене пропами trimBefore/trimAfter.
SEEK=(); [ -n "$FROM" ] && SEEK=(-ss "$FROM")
LIMIT=()
[ -n "$TO" ]  && LIMIT=(-to "$TO")
[ -n "$DUR" ] && LIMIT=(-t "$DUR")

echo "→ Привожу: CFR 30 fps, yuv420p, без звука${CROP:+, кроп $CROP}${TARGET_W:+, ширина $TARGET_W}"
ffmpeg -nostdin -y -loglevel error \
  "${SEEK[@]}" -i "$SRC" "${LIMIT[@]}" \
  -an -vf "$VF" \
  -c:v libx264 -preset slow -crf 18 -pix_fmt yuv420p \
  -movflags +faststart \
  "$OUT"

read -r OUT_W OUT_H <<EOF
$(ffprobe -v error -select_streams v:0 -show_entries stream=width,height -of csv=p=0 "$OUT" | tr ',' ' ')
EOF
OUT_DUR=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$OUT")
OUT_FRAMES=$(awk -v d="$OUT_DUR" 'BEGIN{printf "%d", d*30}')
OUT_MMSS=$(awk -v d="$OUT_DUR" 'BEGIN{printf "%d:%02d", int(d/60), int(d)%60}')
OUT_SIZE=$(du -h "$OUT" | cut -f1)

# ── контактный лист: кадры глазами до сториборда ─────────────────────────────
if [ "$SHEET" -eq 1 ]; then
  # Шесть кадров поперёк клипа — достаточно, чтобы понять, что он вообще
  # показывает и где в нём мёртвый воздух (пауза, перезагрузка, уход фокуса).
  STEP=$(awk -v d="$OUT_DUR" 'BEGIN{s=d/6; if(s<=0)s=0.1; printf "%.4f", 1/s}')
  ffmpeg -nostdin -y -loglevel error -i "$OUT" \
    -vf "fps=${STEP},scale=300:-2,tile=3x2" -frames:v 1 "$SHEET_PNG" 2>/dev/null \
    || echo "  (контактный лист не собрался — клип короче шести кадров)"
fi

# ── строка описи ─────────────────────────────────────────────────────────────
# Дописывается в КОНЕЦ catalog.md отдельной секцией, а не врезается в таблицу:
# в файле несколько таблиц, и автоматическая врезка рано или поздно попала бы
# не в ту. Автор (или агент шага 4б) переносит строку в основную таблицу,
# дописав «что на экране» и «годится для» — это и есть смысловая часть описи,
# её машина не заполнит.
CATALOG="footage/catalog.md"
if ! grep -q "^## Принято скриптом" "$CATALOG" 2>/dev/null; then
  cat >> "$CATALOG" <<'HEAD'

## Принято скриптом — вписать в таблицу выше

Строки ниже дописал `scripts/footage-add.sh`. Техника заполнена машиной,
«что на экране» и «годится для» заполняет человек — и переносит строку в
основную таблицу. Пустая строка здесь = клип снят, но не описан.

| Файл | Что на экране | Тип съёмки | Длит. | Годится для | Использован в |
|---|---|---|---|---|---|
HEAD
fi
printf '| clips/%s.mp4 | ⚠️ ЗАПОЛНИТЬ | ⚠️ ЗАПОЛНИТЬ (%s×%s, 30 fps, %s) | %s | ⚠️ ЗАПОЛНИТЬ | — |\n' \
  "$NAME" "$OUT_W" "$OUT_H" "$OUT_SIZE" "$OUT_MMSS" >> "$CATALOG"

echo ""
echo "✓ Клип в банке: $OUT"
echo "  ${OUT_W}×${OUT_H}, ${OUT_MMSS} (${OUT_FRAMES} кадров @30), ${OUT_SIZE}"
[ "$SHEET" -eq 1 ] && [ -f "$SHEET_PNG" ] && echo "  Контактный лист: $SHEET_PNG — ПОСМОТРЕТЬ ГЛАЗАМИ до сториборда"
echo "  Строка описи дописана в $CATALOG — заполнить «что на экране» и перенести в таблицу"
echo ""
echo "  В сцену: скопировать в engine/public/videos/NN/clips/ и взять <Broll src=\"videos/NN/clips/${NAME}.mp4\" …>"
